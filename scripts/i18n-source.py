HEADER = ""

def js_rx(lang):
    out = []
    for pat, rep in RX:
        r = rep[lang]
        parts, i, expr = [], 0, []
        import re
        tok = re.split(r'(T\(\$\d\)|D\(\$\d\)|\$\d)', r)
        for t in tok:
            if not t: continue
            m = re.fullmatch(r'T\(\$(\d)\)', t)
            if m: expr.append(f"T(g[{m.group(1)}])"); continue
            m = re.fullmatch(r'D\(\$(\d)\)', t)
            if m: expr.append(f"D(g[{m.group(1)}])"); continue
            m = re.fullmatch(r'\$(\d)', t)
            if m: expr.append(f"g[{m.group(1)}]"); continue
            expr.append(json.dumps(t, ensure_ascii=False))
        body = " + ".join(expr) if expr else '""'
        out.append(f"  [/{pat}/, function () {{ var g = arguments; return {body}; }}]")
    return "[\n" + ",\n".join(out) + "\n]"

def build(lang, col):
    d = {}
    for row in ROWS:
        en = " ".join(row[0].split())
        tr = row[col]
        if en in d and d[en] != tr:
            raise SystemExit(f"duplicate key with different text: {en!r}")
        if tr != en:
            d[en] = tr
    body = json.dumps(d, ensure_ascii=False, indent=0, sort_keys=True)
    return HEADER + f"""(function (root) {{
  var dict = {body};
  var T = function (s) {{ return root.I18N ? root.I18N.t(s) : (dict[s] || s); }};
  var D = function (s) {{ return root.I18N ? root.I18N.date(s) : s; }};
  var rx = {js_rx(lang)};
  if (typeof module === 'object' && module.exports) {{ module.exports = {{ dict: dict, rx: rx }}; return; }}
  root.I18N_DICTS = root.I18N_DICTS || {{}};
  root.I18N_DICTS[{json.dumps(lang)}] = dict;
  root.I18N_DICTS[{json.dumps(lang + ':rx')}] = rx;
}})(typeof window !== 'undefined' ? window : globalThis);
"""

